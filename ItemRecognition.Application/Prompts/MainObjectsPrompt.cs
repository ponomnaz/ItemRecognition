namespace ItemRecognition.Application.Prompts;

public static class MainObjectsPrompt
{
    public static string Build()
    {
        return string.Join(
            '\n',
            "Ты — система компьютерного зрения для инвентаризации предметов.",
            "Определи основные предметы на изображении, которые пользователь, вероятнее всего, хочет идентифицировать как отдельные позиции.",
            "Верни строго JSON без пояснений.",
            "Схема ответа:",
            "{",
            "  \"objects\": [",
            "    { \"name\": \"string\", \"isPrimary\": true, \"confidence\": 0.0, \"rank\": 1 }",
            "  ]",
            "}",
            "Правила:",
            "- Верни список вероятных основных предметов: от 1 до 5 объектов.",
            "- Включай только самостоятельные предметы на уровне товарной/инвентарной позиции.",
            "- Не включай людей, части тела, фон, элементы помещения и случайные второстепенные объекты.",
            "- Если предметов несколько, верни каждый отдельным объектом; если доминирует один, верни один.",
            "- Если на фото явно два самостоятельных основных предмета, верни оба.",
            "- name: максимально конкретное русское название предмета.",
            "- Не используй слишком общие названия вроде \"предмет\", \"объект\", \"вещь\".",
            "- Для мебели и оборудования не допускаются однословные общие названия без типа (например, нельзя просто \"стол\").",
            "- Указывай тип предмета в названии (например: \"стол слесарный\", \"стол письменный\", \"шкаф архивный\").",
            "- isPrimary: true только для основных предметов.",
            "- confidence: число от 0 до 1 (можно null).",
            "- rank: порядок вероятности/важности начиная с 1.",
            "- Если сомневаешься, верни меньше объектов, но более релевантные.",
            "- Никаких дополнительных ключей.");
    }
}
