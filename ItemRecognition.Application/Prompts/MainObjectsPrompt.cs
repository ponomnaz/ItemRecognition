namespace ItemRecognition.Application.Prompts;

public static class MainObjectsPrompt
{
    public static string Build()
    {
        return string.Join(
            '\n',
            "Ты — система компьютерного зрения. Определи основные предметы на изображении.",
            "Верни строго JSON без пояснений.",
            "Схема ответа:",
            "{",
            "  \"objects\": [",
            "    { \"name\": \"string\", \"isPrimary\": true, \"confidence\": 0.0, \"rank\": 1 }",
            "  ]",
            "}",
            "Правила:",
            "- Верни список вероятных ОСНОВНЫХ предметов: от 1 до 5 объектов.",
            "- Включай только основные предметы, не фоновые объекты.",
            "- Если на изображении несколько самостоятельных основных предметов, верни каждый отдельным объектом.",
            "- Не объединяй разные предметы в одно общее название.",
            "- name: максимально конкретное русское название предмета.",
            "- Не используй слишком общие названия вроде \"предмет\", \"объект\", \"вещь\".",
            "- isPrimary: true только для основных предметов.",
            "- confidence: число от 0 до 1 (можно null).",
            "- rank: порядок вероятности/важности начиная с 1.",
            "- Никаких дополнительных ключей.");
    }
}
