using System.Text.Json;

namespace ItemRecognition.Application.Prompts;

public static class MaterialsPrompt
{
    public static string Build(IReadOnlyList<string> itemNames)
    {
        var itemsJson = itemNames.Count == 0 ? "[]" : JsonSerializer.Serialize(itemNames);

        return string.Join(
            '\n',
            "Ты — система компьютерного зрения. Определи материалы указанных предметов на изображении.",
            "Верни строго JSON без пояснений и без markdown.",
            "Схема ответа:",
            "{",
            "  \"items\": [",
            "    { \"name\": \"string\", \"materials\": [\"string\"] }",
            "  ]",
            "}",
            "Правила:",
            "- items должен содержать ровно столько объектов, сколько передано предметов, в том же порядке.",
            "- name должен точно совпадать с одним из переданных названий.",
            "- Для каждого предмета верни набор основных материалов (обычно 1-4).",
            "- Для составных предметов укажи материалы корпуса и функциональных частей.",
            "- Используй базовые, обобщенные названия материалов (металл, пластик, дерево, стекло, бумага, ткань, кожа, резина, керамика, камень, композит, чернила и т.п.).",
            "- Если не уверен в частном виде, выбирай более общее название (например, \"металл\" вместо \"сталь\").",
            "- materials: массив без дубликатов, в порядке убывания уверенности.",
            "- Если материал нельзя обоснованно определить или предмет не виден, верни пустой массив.",
            "- Никаких дополнительных ключей.",
            $"Переданные предметы (JSON-массив): {itemsJson}");
    }
}
