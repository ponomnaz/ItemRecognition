namespace ItemRecognition.Application.Prompts;

public static class MaterialsPrompt
{
    public static string Build(IReadOnlyList<string> itemNames)
    {
        var items = itemNames.Count == 0 ? "[]" : string.Join(", ", itemNames);

        return string.Join(
            '\n',
            "Ты — система компьютерного зрения. Определи материалы указанных предметов на изображении.",
            "Верни строго JSON без пояснений.",
            "Схема ответа:",
            "{",
            "  \"items\": [",
            "    { \"name\": \"string\", \"materials\": [\"string\"] }",
            "  ]",
            "}",
            "Правила:",
            "- name должен совпадать с одним из переданных названий.",
            "- Для каждого предмета верни полный набор основных материалов (обычно 1-4).",
            "- Для составных предметов перечисляй и материал корпуса, и материал функциональной части.",
            "- Не ограничивайся одним материалом, если предмет явно составной.",
            "- Используй базовые названия материалов и избегай излишней детализации.",
            "- Для пишущих инструментов учитывай материал корпуса, металлические части и пишущую среду (например, чернила), если это вероятно.",
            "- materials: массив материалов без дубликатов, в порядке убывания уверенности.",
            "- Если материал нельзя обоснованно определить, используй пустой массив.",
            "- Никаких дополнительных ключей.",
            $"Переданные предметы: {items}");
    }
}
